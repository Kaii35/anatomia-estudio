function serie(
  prefix: string,
  base: string,
  enBase: string,
  region: 'mano' | 'pie',
  group: string,
  digits: number[],
  summary: (i: number) => string,
  name: (i: number) => string,
): Bone[] {
  return digits.map((n) => {
    const i = n - 1
    return {
      id: `${prefix}-${n}`,
      name: name(i),
      region,
      group,
      kind: 'largo' as const,
      paired: true,
      series: true,
      aliases: [`${base} ${n}`, `${base} ${ROM[i]}`, `${n} ${base}`, `${ORD[i]} ${base}`],
      mesh: [`${enBase} ${n}`, `${EN_ORD[i]} ${enBase}`, `${n} ${enBase}`],
      summary: summary(i),
    }
  })
}

